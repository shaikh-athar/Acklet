/**
 * Normalizes input extension / format string to canonical key in FORMAT_REGISTRY.
 */
export function normalizeFormatKey(input: string): string {
  const clean = (input || '').toLowerCase().trim().replace(/^\./, '');
  if (clean === 'jpeg') return 'jpg';
  if (clean === 'heif') return 'heic';
  if (clean === 'tif') return 'tiff';
  if (clean === 'fit') return 'fits';
  if (clean === 'pnm') return 'ppm';
  return clean;
}

/**
 * Returns capability entry if supported, or null if unsupported.
 */
export function getFormatCapability(input: string): FormatCapabilityEntry | null {
  const norm = normalizeFormatKey(input);
  return FORMAT_REGISTRY[norm] || null;
}

/**
 * Determines whether the specified extension or format is accepted.
 */
export function isFormatAccepted(input: string): boolean {
  const entry = getFormatCapability(input);
  return !!entry && entry.fileAccepted;
}

/**
 * Returns HTML file input accept attribute string encompassing all supported extensions.
 */
export function getSupportedFileAcceptString(): string {
  const extensions = new Set<string>();
  for (const entry of Object.values(FORMAT_REGISTRY)) {
    for (const ext of entry.extensions) {
      extensions.add(`.${ext}`);
    }
  }
  return 'image/*,' + Array.from(extensions).join(',');
}
